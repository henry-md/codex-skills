/* Load in Outlook's main page to open, and in its native popup to inspect. */
async function openOutlookEML(options) {
  "use strict";
  const fail = (code, message) => ({ ok: false, error: { code, message } });
  if (!options || typeof options !== "object" || Array.isArray(options) ||
      typeof options.mimeBase64 !== "string" || !options.mimeBase64 || options.mimeBase64.length > 14000000 ||
      typeof options.expectedSubject !== "string" || !options.expectedSubject.trim() || options.expectedSubject.length > 998 ||
      typeof options.sourceSHA256 !== "string" || !/^[a-f\d]{64}$/i.test(options.sourceSHA256) ||
      (options.expectedMessageId !== undefined && typeof options.expectedMessageId !== "string") ||
      (options.expectedRunId !== undefined && typeof options.expectedRunId !== "string")) {
    return fail("INVALID_OPTIONS", "Pass bounded base64 MIME, its exact subject and source SHA-256.");
  }
  if (typeof document === "undefined" || !document.defaultView) {
    return fail("BROWSER_REQUIRED", "Run in the signed-in Outlook.com inbox.");
  }
  const doc = document;
  const win = doc.defaultView;
  if (win.location.hostname !== "outlook.live.com" || win.location.protocol !== "https:") {
    return fail("WRONG_ORIGIN", "Open the signed-in HTTPS Outlook.com inbox before loading a file.");
  }
  let bytes;
  let headers;
  let htmlBytes;
  try {
    const encoded = options.mimeBase64.replace(/\s/g, "");
    if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(encoded)) throw new Error();
    const binary = win.atob(encoded);
    bytes = Uint8Array.from(binary, character => character.charCodeAt(0));
    const mime = new win.TextDecoder("utf-8", { fatal: true }).decode(bytes);
    const boundary = /\r?\n\r?\n/.exec(mime);
    if (!boundary || boundary.index > 65536) throw new Error();
    headers = new Map();
    for (const line of mime.slice(0, boundary.index).replace(/\r?\n[ \t]+/g, " ").split(/\r?\n/)) {
      const colon = line.indexOf(":");
      if (colon < 1) throw new Error();
      const key = line.slice(0, colon).toLowerCase();
      if (headers.has(key)) throw new Error();
      headers.set(key, line.slice(colon + 1).trim());
    }
    if (!/^text\/html;\s*charset="?utf-8"?$/i.test(headers.get("content-type") || "") ||
        headers.get("content-transfer-encoding") !== "base64") throw new Error();
    const html = win.atob(mime.slice(boundary.index + boundary[0].length).replace(/\s/g, ""));
    htmlBytes = Uint8Array.from(html, character => character.charCodeAt(0));
  } catch {
    return fail("INVALID_MIME", "Use the complete UTF-8, base64 HTML message generated by preview.py.");
  }
  if (headers.get("subject") !== options.expectedSubject.trim() ||
      headers.get("x-source-hash") !== options.sourceSHA256.toLowerCase() || !headers.get("message-id") ||
      (options.expectedMessageId !== undefined && headers.get("message-id") !== options.expectedMessageId) ||
      (options.expectedRunId !== undefined && headers.get("x-localpreview-run-id") !== options.expectedRunId)) {
    return fail("MIME_IDENTITY_MISMATCH", "The prepared message headers do not match this run.");
  }
  const digest = await win.crypto.subtle.digest("SHA-256", htmlBytes);
  const actualHash = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, "0")).join("");
  if (actualHash !== options.sourceSHA256.toLowerCase()) {
    return fail("MIME_SOURCE_MISMATCH", "The message's decoded HTML does not match the expected source hash.");
  }
  const panes = doc.querySelectorAll('[aria-label="Reading Pane"][role="main"]');
  if (panes.length !== 1) return fail("READING_PANE_NOT_UNIQUE", "Find one native Outlook reading pane before opening a file.");
  const pane = panes[0];
  const rect = pane.getBoundingClientRect();
  const style = win.getComputedStyle(pane);
  const x = rect.x + rect.width / 2;
  const y = rect.y + rect.height / 2;
  if (!pane.getClientRects().length || rect.width <= 0 || rect.height <= 0 ||
      style.visibility === "hidden" || style.display === "none" ||
      x < 0 || y < 0 || x >= win.innerWidth || y >= win.innerHeight) {
    return fail("READING_PANE_NOT_VISIBLE", "Make the Outlook reading pane visible before opening a file.");
  }
  const target = doc.elementFromPoint(x, y);
  if (!target || target === pane || !pane.contains(target) || target.closest('[contenteditable="true"]')) {
    return fail("READING_PANE_TARGET_MISSING", "The pane center must expose a native reading-view descendant, without an editor or overlay.");
  }
  const transfer = new win.DataTransfer();
  transfer.items.add(new win.File([bytes], "message.eml", { type: "message/rfc822" }));
  transfer.effectAllowed = "all";
  transfer.dropEffect = "copy";
  const dispatchedAt = new Date().toISOString();
  const started = win.performance.now();
  for (const type of ["dragenter", "dragover", "drop"]) {
    target.dispatchEvent(new win.DragEvent(type, { bubbles: true, cancelable: true, dataTransfer: transfer, clientX: x, clientY: y }));
  }
  return { ok: true, dispatchedAt, dispatchElapsedMs: Math.round(win.performance.now() - started),
    renderingVerified: false, loadingMethod: "opened-eml", subject: options.expectedSubject.trim(),
    messageId: headers.get("message-id"), sourceSHA256: actualHash };
}

/* Requires browser-inspect.js; selectors were observed in the native opened-.eml popup. */
async function inspectOpenedOutlook(options) {
  "use strict";
  const fail = (code, message, extra = {}) => ({ ok: false, error: { code, message }, ...extra });
  if (!options || typeof options !== "object" || Array.isArray(options)) return fail("INVALID_OPTIONS", "Pass the expected subject, source SHA-256 and ending.");
  const { expectedSubject, sourceSHA256, expectedEnding } = options;
  const timeoutMs = options.timeoutMs === undefined ? 15000 : options.timeoutMs;
  if (typeof expectedSubject !== "string" || !expectedSubject.trim() || expectedSubject.length > 998 ||
      typeof sourceSHA256 !== "string" || !/^[a-f\d]{64}$/i.test(sourceSHA256) ||
      typeof expectedEnding !== "string" || !expectedEnding.trim() || expectedEnding.length > 1000 ||
      !Number.isInteger(timeoutMs) || timeoutMs < 100 || timeoutMs > 60000) {
    return fail("INVALID_OPTIONS", "Use an exact subject, source SHA-256, nonempty ending and timeoutMs from 100 to 60000.");
  }
  if (typeof document === "undefined" || !document.defaultView) return fail("BROWSER_REQUIRED", "Run in Outlook's native opened-message popup.");
  if (typeof inspectEmailDOM !== "function") return fail("INSPECTOR_NOT_LOADED", "Load browser-inspect.js before inspecting the Outlook message.");
  const doc = document;
  const win = doc.defaultView;
  const started = win.performance.now();
  const deadline = started + timeoutMs;
  const subject = expectedSubject.trim();
  const rootSelector = 'div[id^="UniqueMessageBody_"][aria-label="Message body"]';
  const normalize = value => value.replace(/\s+/g, " ").trim();
  const visible = node => node.getClientRects().length > 0 && !["hidden", "collapse"].includes(win.getComputedStyle(node).visibility);
  function identify() {
    if (!doc.title.startsWith(subject + " - ")) return { reason: "popup-title-not-matched" };
    const headings = Array.from(doc.querySelectorAll('[role="heading"].Xz4k3')).filter(visible);
    if (headings.length !== 1 || headings[0].textContent.trim() !== subject) return { reason: "subject-not-matched" };
    const bodies = doc.querySelectorAll(rootSelector);
    if (bodies.length !== 1) return { reason: "message-body-not-unique" };
    const body = bodies[0];
    if (!visible(body)) return { reason: "message-body-not-visible" };
    const text = typeof body.innerText === "string" ? body.innerText : body.textContent || "";
    if (!normalize(text).includes(normalize(expectedEnding))) return { reason: "ending-not-found" };
    return { body, heading: headings[0], endingPresent: true };
  }
  let lastReason = "message-not-found";
  const identity = await new Promise(resolve => {
    let timer;
    const observer = new win.MutationObserver(check);
    function finish(value) { observer.disconnect(); win.clearTimeout(timer); resolve(value); }
    function check() {
      const current = identify();
      if (current.body) finish(current);
      else lastReason = current.reason;
    }
    observer.observe(doc.documentElement, { subtree: true, childList: true, characterData: true, attributes: true,
      attributeFilter: ["class", "id", "aria-label", "style", "hidden", "aria-hidden"] });
    timer = win.setTimeout(() => finish(null), timeoutMs);
    check();
  });
  const nativeIdentity = { loadingMethod: "opened-eml", subject, endingPresent: !!identity,
    sourceHashProvenance: "Supplied from the verified prepared MIME; not extracted from Outlook's rendered body." };
  if (!identity) return fail(lastReason === "ending-not-found" ? "OUTLOOK_ENDING_NOT_FOUND" : "OUTLOOK_MESSAGE_TIMEOUT",
    "The expected Outlook popup subject, visible body and ending did not become ready.",
    { nativeIdentity, waitReason: lastReason, elapsedMs: Math.round(win.performance.now() - started) });
  const identityReadyMs = Math.round(win.performance.now() - started);
  const remaining = Math.floor(deadline - win.performance.now());
  if (remaining < 100) return fail("OUTLOOK_MESSAGE_TIMEOUT", "No inspection time remained after identifying the message.", { nativeIdentity });
  let inspected;
  try {
    inspected = await inspectEmailDOM({ rootSelector, waitForReady: true, sourceSHA256, client: "outlook-web",
      readinessTimeoutMs: Math.min(10000, remaining) });
  } catch { return fail("INSPECTION_FAILED", "The Outlook message DOM could not be inspected.", { nativeIdentity }); }
  const current = identify();
  if (!current.body || current.body !== identity.body || current.heading !== identity.heading) {
    return fail("OUTLOOK_MESSAGE_CHANGED", "The expected message changed during inspection; open it again.",
      { nativeIdentity: { ...nativeIdentity, endingPresent: !!current.endingPresent }, waitReason: current.reason || "message-body-replaced" });
  }
  return { ...inspected, nativeIdentity, identityReadyMs, elapsedMs: Math.round(win.performance.now() - started) };
}

if (typeof module !== "undefined" && module.exports) module.exports = { openOutlookEML, inspectOpenedOutlook };
({ opener: "openOutlookEML", inspector: "inspectOpenedOutlook" });
